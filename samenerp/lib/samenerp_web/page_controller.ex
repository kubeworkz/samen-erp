defmodule SamenerpWeb.PageController do
  @moduledoc """
  The Samenerp landing + health endpoints.

  `/` serves the public MARKETING homepage, read from `priv/homepage.html`. The
  page is a plain HTML artifact authored outside Elixir (it used to be a heredoc
  here), so a copy change is an HTML edit, not a controller edit — this module
  only owns the route and the bytes. It is read per request rather than embedded
  at compile time so the file stays the single source of truth for marketing.

  `/healthz` returns `ok` (the LIVENESS probe — the BEAM is up).
  `/readyz` is the READINESS probe — it returns 200 only when Postgres, the KMS
  wrapped-DEK store, and Oban all answer (`Samen.Web.Readiness`), else 503.

  A missing homepage file RAISES rather than serving an empty 200: the landing
  page is a required artifact, and a blank homepage is the kind of silent lie the
  gates exist to prevent (ADR-014 fail-honest).
  """
  use Phoenix.Controller, formats: [:html]

  import Plug.Conn

  # Path relative to this app's priv dir. `Application.app_dir/2` (NOT a
  # compile-time `:code.priv_dir/1`) so the same code resolves the release's priv
  # directory, not the build machine's.
  @homepage "homepage.html"

  def index(conn, _params) do
    html(conn, homepage!())
  end

  def healthz(conn, _params) do
    send_resp(conn, 200, "ok")
  end

  # API Docs surface (README "API Documentation" card) — the host's OpenAPI 3.0
  # spec, generated by `Samenerp.ApiDocs` from the SAME Ash resource surface the
  # `/api/v1` JSON:API endpoint serves. Static artifact: no actor, no org, no
  # request data in the document.
  def openapi(conn, _params) do
    Samenerp.ApiDocs.serve_spec(conn)
  end

  def readyz(conn, _params) do
    case Samen.Web.Readiness.check(repo: Samenerp.Repo) do
      {:ok, _checks} ->
        send_resp(conn, 200, "ready")

      {:error, checks} ->
        body =
          Enum.map_join(checks, "\n", fn
            {component, :ok} -> "#{component}: ok"
            {component, {:error, _reason}} -> "#{component}: FAIL"
          end)

        send_resp(conn, 503, "not ready\n" <> body)
    end
  end

  defp homepage! do
    path = Application.app_dir(:samenerp, Path.join("priv", @homepage))

    case File.read(path) do
      {:ok, body} ->
        body

      {:error, reason} ->
        raise "SamenerpWeb.PageController: the marketing homepage is missing at #{path} " <>
                "(#{:file.format_error(reason)}) — GET / serves priv/#{@homepage} verbatim; " <>
                "ship the file, do not fall back to a blank page"
    end
  end
end
